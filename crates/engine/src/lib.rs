/// What the renderer needs to know about one node.
#[derive(Clone, Debug, PartialEq)]
pub struct NodeDesc {
    pub pos: [f32; 2],
    pub size: [f32; 2],
    pub kind: Kind,
    pub content: Content,
    /// Placeholder color (RGBA8, red in the low byte): shown until pixels are resident and
    /// behind transparent pixels (alpha 0 = see-through); the fill of [`Kind::Flat`] nodes.
    pub color: u32,
    /// Content aspect ratio (w/h). Tiles hold the content squeezed to a square; the shader
    /// restores it with a centered cover crop. 0 = use the node's own aspect.
    pub aspect: f32,
    /// Maximum corner radius in screen pixels; negative = `-radius` in world units (scales
    /// with zoom, up to half the node's size).
    pub radius: f32,
    pub hidden: bool,
    /// A text raster (note / text node): never takes a [`Tier::Hires`] slot; once it is big
    /// on screen the page draws crisp DOM text over it.
    pub text: bool,
    /// Draw as a generating tile: the fal mark as stepped LED dots over `color` (one shader
    /// effect, no CPU work per frame).
    pub generating: Option<GenTile>,
    /// A text raster under transparent DOM text: fades out between these camera zooms (CSS px
    /// per world unit) while the page's text fades in over it.
    pub text_fade: Option<[f32; 2]>,
}

/// A generation placeholder drawn by the shader (see [`NodeDesc::gen`]).
