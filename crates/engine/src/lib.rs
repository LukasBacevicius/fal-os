/// One overlay primitive (see `overlay.wgsl`). Screen sizes are in physical pixels.
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, bytemuck::Pod, bytemuck::Zeroable)]
pub struct OverlayPrim {
    /// World-space anchor (top-left of the primitive before `px_offset`).
    pub world: [f32; 2],
    /// World-space size (scales with zoom).
    pub world_size: [f32; 2],
    /// Screen-space offset added to the anchor.
    pub px_offset: [f32; 2],
    /// Screen-space size added to the world size.
    pub px_size: [f32; 2],
    /// RGBA8 colors (red in the low byte); alpha is honored.
    pub fill: u32,
    pub stroke: u32,
    pub stroke_px: f32,
    pub radius_px: f32,
    pub shape: u32,
    /// Activity shapes (`STEP`, `STEP_DASHED`): start time on the renderer clock (seconds, the
    /// `time` passed to [`Renderer::render`]), and duration (0 = persistent).
    pub t0: f32,
    pub dur: f32,
    /// Per-primitive random seed (dot patterns).
    pub seed: f32,
}

impl OverlayPrim {
    pub const RECT: u32 = 0;
    pub const CIRCLE: u32 = 1;
    pub const CURSOR: u32 = 2;
    pub const DASHED: u32 = 3;
    pub const PIN: u32 = 4;
    /// Agent activity (UX-V1 §4), stepped in the shader from `t0`/`dur` and the clock: a 1 px
    /// outline that holds, then steps down in three levels (writes, edits, child outlines).
    pub const STEP: u32 = 5;
    /// The same, dashed (reads, deletes).
    pub const STEP_DASHED: u32 = 6;
    /// A tiny mono provenance badge (docs/ASSETS-V1.md §5): a glyph (`seed`, one of the
    /// `BADGE_*` ids) in `stroke` on a faint `fill` square, constant size on screen. `t0`/`dur` carry the
    /// node's world width/height: the shader hides the badge while the node is small on
    /// screen. Not animated.
    pub const GLYPH: u32 = 7;

    /// Badge glyphs: `↓` import, `✦` generated, `ƒ` derived, `▶` render, `★` final, and the
    /// `↑` dot (uploaded to fal).
    pub const BADGE_IMPORT: u32 = 0;
    pub const BADGE_GENERATE: u32 = 1;
    pub const BADGE_DERIVE: u32 = 2;
    pub const BADGE_RENDER: u32 = 3;
    pub const BADGE_FINAL: u32 = 4;
    pub const BADGE_UPLOADED: u32 = 5;

    /// Whether the shape animates (needs frames while live).
    pub fn animated(&self) -> bool {
        self.shape == Self::STEP || self.shape == Self::STEP_DASHED
    }

    /// A badge of `px` physical pixels at the node's top-left corner (inset 3 px), `slot`
    /// badges to the right. `node_size`: the world size the shader tests against its
    /// minimum on-screen size (pass something huge to always show it).
    pub fn glyph(node: [f32; 4], node_size: [f32; 2], glyph: u32, slot: f32, px: f32, [fill, stroke]: [u32; 2], dpr: f32) -> Self {
        Self {
            world: [node[0], node[1]],
            px_offset: [3.0 * dpr + slot * (px + dpr), 3.0 * dpr],
            px_size: [px; 2],
            fill,
            stroke,
            stroke_px: 1.1 * dpr,
            shape: Self::GLYPH,
            t0: node_size[0],
            dur: node_size[1],
            seed: glyph as f32,
            ..Self::zeroed()
        }
    }

    /// An animated world rect: `shape` is one of the activity shapes.
    pub fn activity(r: [f32; 4], shape: u32, fill: u32, stroke: u32, stroke_px: f32, t0: f32, dur: f32) -> Self {
        Self { shape, t0, dur, ..Self::rect(r, fill, stroke, stroke_px) }
    }

    /// A world-space rect `[x, y, w, h]`.
    pub fn rect(r: [f32; 4], fill: u32, stroke: u32, stroke_px: f32) -> Self {
        Self { world: [r[0], r[1]], world_size: [r[2], r[3]], fill, stroke, stroke_px, ..Self::zeroed() }
    }

    /// A world-space rect drawn with a dashed stroke (marquee).
    pub fn dashed(r: [f32; 4], fill: u32, stroke: u32, stroke_px: f32) -> Self {
        Self { shape: Self::DASHED, ..Self::rect(r, fill, stroke, stroke_px) }
    }

    /// A constant-size square centered on a world point (resize handle).
    pub fn handle(p: [f32; 2], px: f32, fill: u32, stroke: u32, stroke_px: f32) -> Self {
        Self {
            world: p,
            px_offset: [-px * 0.5; 2],
            px_size: [px; 2],
            fill,
            stroke,
            stroke_px,
            radius_px: 1.0,
            ..Self::zeroed()
        }
    }

    /// A constant-size circle centered on a world point.
    pub fn dot(p: [f32; 2], px: f32, fill: u32, stroke: u32, stroke_px: f32) -> Self {
        Self { shape: Self::CIRCLE, ..Self::handle(p, px, fill, stroke, stroke_px) }
    }

    /// A comment pin whose pointed corner sits on the world point.
    pub fn pin(p: [f32; 2], px: f32, fill: u32, stroke: u32, stroke_px: f32) -> Self {
        Self {
            world: p,
            px_offset: [0.0, -px],
            px_size: [px; 2],
            fill,
            stroke,
            stroke_px,
            shape: Self::PIN,
            ..Self::zeroed()
        }
    }

    /// A cursor arrow with its tip at the world point.
    pub fn cursor(p: [f32; 2], px: f32, fill: u32, stroke: u32) -> Self {
        Self { world: p, px_size: [px; 2], fill, stroke, stroke_px: 1.5, shape: Self::CURSOR, ..Self::zeroed() }
    }

    fn zeroed() -> Self {
        bytemuck::Zeroable::zeroed()
    }
}

