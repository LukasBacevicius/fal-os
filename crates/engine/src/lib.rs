/// Pixels handed to [`Renderer::provide_low`] / [`Renderer::provide_detail`].
pub enum Pixels<'a> {
    /// Straight-alpha RGBA8 of any size; resampled on the CPU into the tile.
    Rgba { width: u32, height: u32, data: &'a [u8] },
    /// A browser image source (`ImageBitmap`, canvas, `<video>`…) that the caller already
    /// resized to [`Renderer::tile_size`] (e.g. `createImageBitmap(blob, {resizeWidth,
    /// resizeHeight})`). Copied on the GPU with `copyExternalImageToTexture`, mips generated on
    /// the GPU.
    #[cfg(target_arch = "wasm32")]
    External(wgpu::ExternalImageSource),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Tier {
    /// 32 px, always resident for every node.
    Low,
    /// 256 px slots, LRU.
    Detail,
    /// 1024 px slots for the few nodes that are big on screen, LRU.
    Hires,
}

fn tier_dims(tier: Tier) -> (u32, u32) {
    match tier {
        Tier::Low => (LOW_TILE, LOW_MIPS),
        Tier::Detail => (DETAIL_TILE, DETAIL_MIPS),
        Tier::Hires => (HIRES_TILE, HIRES_MIPS),
    }
}

