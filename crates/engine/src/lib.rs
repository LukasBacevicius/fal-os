//! fal-os canvas engine.
//!
//! Platform-independent wgpu renderer: Metal natively, WebGPU in wasm. Techniques borrowed
//! from the Brilliant teardown (docs/research/brilliant-renderer.md):
//! - camera-only frames write one uniform; instances are rewritten only in their dirty range
//! - one instanced draw for every node, SDF corners with zoom-independent AA
//! - sub-pixel nodes collapse to zero area instead of changing the draw list
//! - two texture tiers: an always-resident 32px mipmapped tier for every node, and a
//!   256px detail tier with a fixed slot budget and LRU eviction
//! - per-frame upload budgets, progressive cold open, and a cap on active video decoders
//! - pluggable real video decode ([`media::VideoSource`]); new frames are GPU-blitted into detail slots
//!
//! The scene is dynamic: nodes are added, updated and removed through stable [`Handle`]s
//! (slots with a free list). Pixels for [`Content::External`] nodes come from the platform:
//! the low tier is pushed once with [`Renderer::provide_low`]; detail tiles are pulled on demand
//! ([`Renderer::take_requests`] → [`Renderer::provide`]; 256 px detail and 1024 px hires tiers) and evicted by LRU, so only
//! what is on screen holds detail memory. A small overlay pass ([`OverlayPrim`]) draws the
//! canvas-level UI (selection, handles, marquee, annotation pins, remote cursors).

