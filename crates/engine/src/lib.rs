#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Camera {
    /// World position of the viewport's top-left corner.
    pub offset: [f32; 2],
    /// Physical pixels per world unit.
    pub zoom: f32,
    /// Viewport size in physical pixels.
    pub viewport: [f32; 2],
}

impl Camera {
    pub const MIN_ZOOM: f32 = 0.002;
    pub const MAX_ZOOM: f32 = 64.0;

    pub fn screen_to_world(&self, p: [f32; 2]) -> [f32; 2] {
        [self.offset[0] + p[0] / self.zoom, self.offset[1] + p[1] / self.zoom]
    }

    pub fn world_to_screen(&self, p: [f32; 2]) -> [f32; 2] {
        [(p[0] - self.offset[0]) * self.zoom, (p[1] - self.offset[1]) * self.zoom]
    }

    pub fn pan(&mut self, dx: f32, dy: f32) {
        self.offset[0] -= dx / self.zoom;
        self.offset[1] -= dy / self.zoom;
    }

    pub fn zoom_at(&mut self, screen: [f32; 2], factor: f32) {
        let before = self.screen_to_world(screen);
        self.zoom = (self.zoom * factor).clamp(Self::MIN_ZOOM, Self::MAX_ZOOM);
        let after = self.screen_to_world(screen);
        self.offset[0] += before[0] - after[0];
        self.offset[1] += before[1] - after[1];
    }

    /// Frames the world rect `[x, y, w, h]`, never zooming in past `max_zoom`.
    pub fn fit_max(&mut self, rect: [f32; 4], max_zoom: f32) {
        let (w, h) = (rect[2].max(1.0), rect[3].max(1.0));
        self.zoom = ((self.viewport[0] / w).min(self.viewport[1] / h) * 0.9).clamp(Self::MIN_ZOOM, max_zoom);
        self.offset = [
            rect[0] + rect[2] * 0.5 - self.viewport[0] * 0.5 / self.zoom,
            rect[1] + rect[3] * 0.5 - self.viewport[1] * 0.5 / self.zoom,
        ];
    }

    /// Frames the world rect `[x, y, w, h]`.
    pub fn fit(&mut self, rect: [f32; 4]) {
        self.fit_max(rect, Self::MAX_ZOOM);
    }
}

