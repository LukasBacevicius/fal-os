struct DetailCache {
    free: Vec<u32>,
    slot_node: Vec<Option<Handle>>,
    last_used: Vec<u64>,
    node_slot: HashMap<Handle, u32>,
}

impl DetailCache {
    fn new(capacity: u32) -> Self {
        Self {
            free: (0..capacity).rev().collect(),
            slot_node: vec![None; capacity as usize],
            last_used: vec![0; capacity as usize],
            node_slot: HashMap::new(),
        }
    }

    /// Returns a slot for `node`, evicting the least-recently-used slot not touched this frame.
    fn alloc(&mut self, node: Handle, frame: u64) -> Option<(u32, Option<Handle>)> {
        let slot = match self.free.pop() {
            Some(s) => s,
            None => {
                let (s, &t) = self.last_used.iter().enumerate().min_by_key(|(_, t)| **t)?;
                if t >= frame {
                    return None;
                }
                s as u32
            }
        };
        let evicted = self.slot_node[slot as usize].take();
        if let Some(e) = evicted {
            self.node_slot.remove(&e);
        }
        self.slot_node[slot as usize] = Some(node);
        self.node_slot.insert(node, slot);
        self.last_used[slot as usize] = frame;
        Some((slot, evicted))
    }

    fn release(&mut self, node: Handle) {
        if let Some(slot) = self.node_slot.remove(&node) {
            self.slot_node[slot as usize] = None;
            self.last_used[slot as usize] = 0;
            self.free.push(slot);
        }
    }
}

